def hashlib_file(path: pathlib.Path) -> str:
    import hashlib

    digest = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="role", required=True)
    provider = subparsers.add_parser("provider")
    provider.add_argument("--listen-ip", required=True)
    provider.add_argument("--bootstrap-port", type=int, default=8079)
    provider.add_argument("--build-dir")
    provider.add_argument("--result-root", default="/tmp/mooncake-egm-gb200")
    provider.add_argument("--timeout-sec", type=int, default=6 * 60 * 60)
    provider.add_argument("--skip-build", action="store_true")
