def run(
    command: list[str],
    *,
    env: Mapping[str, str] | None = None,
    stdout=None,
    stderr=None,
    check: bool = True,
    cwd: pathlib.Path | None = None,
) -> subprocess.CompletedProcess[str]:
    print("+ " + shlex.join(command), flush=True)
    return subprocess.run(
        command,
        check=check,
        text=True,
        env=dict(env) if env is not None else None,
        stdout=stdout,
        stderr=stderr,
        cwd=cwd,
    )


def git_value(repo_root: pathlib.Path, *args: str) -> str:
    return subprocess.check_output(
        ["git", "-C", str(repo_root), *args], text=True
    ).strip()


def write_config(path: pathlib.Path, values: Mapping[str, object]) -> None:
    lines = ["# Generated by egm_store_orchestrator.py; do not edit during a run."]
    for name, value in values.items():
        if isinstance(value, str):
            lines.append(f"{name}={shlex.quote(value)}")
        else:
            lines.append(f"{name}={value}")
    path.write_text("\n".join(lines) + "\n")


def wait_process_log_marker(
    process: subprocess.Popen[str],
    log_path: pathlib.Path,
    marker: str,
    label: str,
    timeout: float = 60,
) -> None:
    deadline = time.monotonic() + timeout
    log_text = ""
    while time.monotonic() < deadline:
        if log_path.exists():
            log_text = log_path.read_text(errors="replace")
            if marker in log_text:
                return
        returncode = process.poll()
        if returncode is not None:
            raise RuntimeError(
                f"{label} exited rc={returncode} before readiness marker; "
                f"log tail:\n{log_text[-4096:]}"
            )
        time.sleep(0.5)
    raise RuntimeError(
        f"{label} did not emit readiness marker within {timeout:g}s; "
        f"log tail:\n{log_text[-4096:]}"
    )


def stop_process(
    process: subprocess.Popen[str] | None, label: str
) -> dict[str, object]:
    if process is None:
        return {"label": label, "status": "NOT_STARTED"}
    if process.poll() is None:
        process.terminate()
        try:
            process.wait(timeout=30)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=10)
    return {"label": label, "status": "PASS", "returncode": process.returncode}


